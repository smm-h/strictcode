// Package gen generates the Go vocabulary constants (internal/vocab) from
// schema/vocabulary.toml and schema/profiles/*.toml. The documents are loaded
// through the strictspec-generated readers, so generation is impossible from
// an invalid document — a diagnostic is a hard error.
//
// The output is deterministic: source order of the vocabulary and profile
// documents is preserved, so the same inputs always produce the same bytes.
package gen

import (
	"fmt"
	goformat "go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/smm-h/strictcode/internal/spec/profilespec"
	"github.com/smm-h/strictcode/internal/spec/vocabspec"
	"github.com/smm-h/strictspec/go/strictspec"
)

// profileFiles maps the profile language code to its document path, in
// emission order.
var profileFiles = []struct {
	lang string
	path string
}{
	{"py", "schema/profiles/python.toml"},
	{"go", "schema/profiles/go.toml"},
	{"ts", "schema/profiles/ts-js.toml"},
}

// Generate produces the contents of internal/vocab/vocab_gen.go from the
// schema documents under repoRoot.
func Generate(repoRoot string) ([]byte, error) {
	vocabPath := filepath.Join(repoRoot, "schema", "vocabulary.toml")
	raw, err := os.ReadFile(vocabPath)
	if err != nil {
		return nil, fmt.Errorf("vocabgen: %w", err)
	}
	v, diags := vocabspec.ValidateBytes(raw, "toml")
	if v == nil {
		return nil, fmt.Errorf("vocabgen: %s is invalid: %v", vocabPath, diags)
	}

	type profile struct {
		lang string
		doc  *profilespec.Profile
	}
	var profiles []profile
	for _, pf := range profileFiles {
		p := filepath.Join(repoRoot, pf.path)
		rawP, err := os.ReadFile(p)
		if err != nil {
			return nil, fmt.Errorf("vocabgen: %w", err)
		}
		doc, pdiags := profilespec.ValidateBytes(rawP, "toml")
		if doc == nil {
			return nil, fmt.Errorf("vocabgen: %s is invalid: %v", p, pdiags)
		}
		if doc.Language != pf.lang {
			return nil, fmt.Errorf("vocabgen: %s declares language %q, expected %q", p, doc.Language, pf.lang)
		}
		profiles = append(profiles, profile{pf.lang, doc})
	}

	// Closed-set check: profiles must declare exactly the vocabulary's
	// capabilities (SPEC.md section 5 — unknown capability names are hard
	// errors at generation time).
	capSet := map[string]bool{}
	for _, c := range v.Capabilities {
		capSet[c.Id] = true
	}
	for _, p := range profiles {
		declared := map[string]bool{}
		for _, kv := range p.doc.Capabilities.Entries() {
			if !capSet[kv.Key] {
				return nil, fmt.Errorf("vocabgen: profile %s declares unknown capability %q", p.lang, kv.Key)
			}
			declared[kv.Key] = true
		}
		for id := range capSet {
			if !declared[id] {
				return nil, fmt.Errorf("vocabgen: profile %s missing status for capability %q", p.lang, id)
			}
		}
	}

	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("// Code generated by vocabgen from schema/vocabulary.toml and schema/profiles/. DO NOT EDIT.\n")
	w("//\n// Regenerate: go run ./cmd/vocabgen\n")
	w("// Freshness is enforced by TestGeneratedVocabIsFresh (go test ./internal/vocab).\n\n")
	w("package vocab\n\n")

	// --- Node kinds ---
	w("// NodeKind is a vocabulary node kind identifier.\ntype NodeKind string\n\nconst (\n")
	for _, nk := range v.NodeKinds {
		w("\tNodeKind%s NodeKind = %q\n", ident(nk.Id), nk.Id)
	}
	w(")\n\n")
	w("// NodeKinds lists every node kind in vocabulary order.\nvar NodeKinds = []NodeKind{\n")
	for _, nk := range v.NodeKinds {
		w("\tNodeKind%s,\n", ident(nk.Id))
	}
	w("}\n\n")

	// --- Row kinds ---
	w("// RowKind is a vocabulary interaction-row kind identifier.\ntype RowKind string\n\nconst (\n")
	for _, rk := range v.RowKinds {
		w("\tRowKind%s RowKind = %q\n", ident(rk.Id), rk.Id)
	}
	w(")\n\n")
	w("// RowKinds lists every row kind in vocabulary order.\nvar RowKinds = []RowKind{\n")
	for _, rk := range v.RowKinds {
		w("\tRowKind%s,\n", ident(rk.Id))
	}
	w("}\n\n")

	// --- Shared metadata types ---
	w(`// Maturity is the vocabulary maturity marker.
type Maturity string

const (
	MaturityStable      Maturity = "stable"
	MaturitySpeculative Maturity = "speculative"
)

// AttrType is the type of a declared attribute.
type AttrType int

const (
	AttrString AttrType = iota
	AttrBool
	AttrInt
	AttrEnum
)

// AttrDecl declares one typed attribute of a node kind or row kind.
// For AttrEnum, Enum names the vocabulary enum carrying the legal values.
type AttrDecl struct {
	Name string
	Type AttrType
	Enum string
}

// NodeKindDecl is the vocabulary declaration of a node kind.
type NodeKindDecl struct {
	Maturity Maturity
	Attrs    []AttrDecl
}

// RowKindDecl is the vocabulary declaration of a row kind.
type RowKindDecl struct {
	Maturity Maturity
	SrcKinds []NodeKind
	DstKinds []NodeKind
	Attrs    []AttrDecl
}

`)

	// --- Node kind info ---
	w("// NodeKindInfo carries the vocabulary declaration for every node kind.\nvar NodeKindInfo = map[NodeKind]NodeKindDecl{\n")
	for _, nk := range v.NodeKinds {
		w("\tNodeKind%s: {\n\t\tMaturity: %s,\n", ident(nk.Id), maturityConst(nk.Maturity))
		if len(nk.Attributes) > 0 {
			w("\t\tAttrs: []AttrDecl{\n")
			for _, a := range nk.Attributes {
				decl, err := attrDecl(a.Name, a.Type)
				if err != nil {
					return nil, err
				}
				w("\t\t\t%s,\n", decl)
			}
			w("\t\t},\n")
		}
		w("\t},\n")
	}
	w("}\n\n")

	// --- Row kind info ---
	w("// RowKindInfo carries the vocabulary declaration for every row kind.\nvar RowKindInfo = map[RowKind]RowKindDecl{\n")
	for _, rk := range v.RowKinds {
		w("\tRowKind%s: {\n\t\tMaturity: %s,\n", ident(rk.Id), maturityConst(rk.Maturity))
		w("\t\tSrcKinds: []NodeKind{%s},\n", kindList(rk.SrcKinds))
		w("\t\tDstKinds: []NodeKind{%s},\n", kindList(rk.DstKinds))
		if len(rk.Attributes) > 0 {
			w("\t\tAttrs: []AttrDecl{\n")
			for _, a := range rk.Attributes {
				decl, err := attrDecl(a.Name, a.Type)
				if err != nil {
					return nil, err
				}
				w("\t\t\t%s,\n", decl)
			}
			w("\t\t},\n")
		}
		w("\t},\n")
	}
	w("}\n\n")

	// --- Enums ---
	w("// Enums carries every vocabulary enum and its legal values.\nvar Enums = map[string][]string{\n")
	for _, e := range v.Enums {
		vals := make([]string, len(e.Values))
		for i, val := range e.Values {
			vals[i] = fmt.Sprintf("%q", val)
		}
		w("\t%q: {%s},\n", e.Id, strings.Join(vals, ", "))
	}
	w("}\n\n")

	// --- Capabilities and layers ---
	w("// Capability is a fine-grained extraction capability identifier.\ntype Capability string\n\nconst (\n")
	for _, c := range v.Capabilities {
		w("\tCap%s Capability = %q\n", ident(c.Id), c.Id)
	}
	w(")\n\n")
	w("// Capabilities lists every capability in vocabulary order.\nvar Capabilities = []Capability{\n")
	for _, c := range v.Capabilities {
		w("\tCap%s,\n", ident(c.Id))
	}
	w("}\n\n")

	w("// Layer is a named capability bundle.\ntype Layer string\n\nconst (\n")
	for _, l := range v.Layers {
		w("\tLayer%s Layer = %q\n", ident(l.Id), l.Id)
	}
	w(")\n\n")
	w("// CapabilityLayer maps every capability to its layer.\nvar CapabilityLayer = map[Capability]Layer{\n")
	for _, c := range v.Capabilities {
		w("\tCap%s: Layer%s,\n", ident(c.Id), ident(c.Layer))
	}
	w("}\n\n")

	// --- Languages and profiles ---
	w(`// Lang is a profile language code (one column of the matrix).
type Lang string

const (
	LangPy Lang = "py"
	LangGo Lang = "go"
	LangTS Lang = "ts"
)

// Langs lists the language trio in matrix column order.
var Langs = []Lang{LangPy, LangGo, LangTS}

// CapabilityStatus is a profile's declared status for one capability.
type CapabilityStatus string

const (
	StatusSupported     CapabilityStatus = "supported"
	StatusPlanned       CapabilityStatus = "planned"
	StatusNotApplicable CapabilityStatus = "not-applicable"
)

// ProfileCapability is a capability status plus the mandatory reason when
// the status is not-applicable.
type ProfileCapability struct {
	Status CapabilityStatus
	Reason string
}

// Profile is a language profile: display identity plus per-capability status.
type Profile struct {
	DisplayName  string
	Grammar      string
	Capabilities map[Capability]ProfileCapability
}

`)
	w("// Profiles carries the language profiles from schema/profiles/.\nvar Profiles = map[Lang]Profile{\n")
	for _, p := range profiles {
		w("\t%s: {\n\t\tDisplayName: %q,\n\t\tGrammar: %q,\n\t\tCapabilities: map[Capability]ProfileCapability{\n",
			langConst(p.lang), p.doc.DisplayName, p.doc.Grammar)
		// Emit in vocabulary capability order for determinism (profile map
		// order is incidental per the schema).
		statuses := map[string]struct {
			status string
			reason string
		}{}
		for _, kv := range p.doc.Capabilities.Entries() {
			status, _ := stringField(kv.Value, "status")
			reason, _ := stringField(kv.Value, "reason")
			statuses[kv.Key] = struct {
				status string
				reason string
			}{status, reason}
		}
		for _, c := range v.Capabilities {
			st := statuses[c.Id]
			if st.reason == "" {
				w("\t\t\tCap%s: {Status: %s},\n", ident(c.Id), statusConst(st.status))
			} else {
				w("\t\t\tCap%s: {Status: %s, Reason: %q},\n", ident(c.Id), statusConst(st.status), st.reason)
			}
		}
		w("\t\t},\n\t},\n")
	}
	w("}\n")

	formatted, err := goformat.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("vocabgen: generated source does not parse: %w", err)
	}
	return formatted, nil
}

// ident converts a vocabulary identifier (snake_case or kebab-case) to a Go
// exported identifier fragment.
func ident(id string) string {
	parts := strings.FieldsFunc(id, func(r rune) bool { return r == '_' || r == '-' })
	var sb strings.Builder
	for _, p := range parts {
		sb.WriteString(strings.ToUpper(p[:1]))
		sb.WriteString(p[1:])
	}
	return sb.String()
}

func maturityConst(m string) string {
	switch m {
	case "stable":
		return "MaturityStable"
	case "speculative":
		return "MaturitySpeculative"
	}
	panic(fmt.Sprintf("vocabgen: unknown maturity %q (schema validation should have rejected it)", m))
}

func statusConst(s string) string {
	switch s {
	case "supported":
		return "StatusSupported"
	case "planned":
		return "StatusPlanned"
	case "not-applicable":
		return "StatusNotApplicable"
	}
	panic(fmt.Sprintf("vocabgen: unknown capability status %q (schema validation should have rejected it)", s))
}

func langConst(l string) string {
	switch l {
	case "py":
		return "LangPy"
	case "go":
		return "LangGo"
	case "ts":
		return "LangTS"
	}
	panic(fmt.Sprintf("vocabgen: unknown language %q (schema validation should have rejected it)", l))
}

func attrDecl(name, typ string) (string, error) {
	switch {
	case typ == "string":
		return fmt.Sprintf("{Name: %q, Type: AttrString}", name), nil
	case typ == "boolean":
		return fmt.Sprintf("{Name: %q, Type: AttrBool}", name), nil
	case typ == "integer":
		return fmt.Sprintf("{Name: %q, Type: AttrInt}", name), nil
	case strings.HasPrefix(typ, "enum:"):
		return fmt.Sprintf("{Name: %q, Type: AttrEnum, Enum: %q}", name, strings.TrimPrefix(typ, "enum:")), nil
	}
	return "", fmt.Errorf("vocabgen: attribute %q has unknown type %q", name, typ)
}

// kindList renders a []NodeKind literal body from vocabulary kind ids.
func kindList(ids []string) string {
	parts := make([]string, len(ids))
	for i, id := range ids {
		parts[i] = "NodeKind" + ident(id)
	}
	return strings.Join(parts, ", ")
}

// stringField extracts a string field from a strictspec record value; the
// boolean reports presence.
func stringField(v strictspec.Value, name string) (string, bool) {
	fv, ok := v.Field(name)
	if !ok {
		return "", false
	}
	return fv.AsString()
}
